const DICTIONARIES: Record<Locale, Dictionary> = { en, uk, ja }

export function getDictionary(locale: Locale) {
  const t = DICTIONARIES[locale]
  const code = LOCALE_LABEL[locale]
  return {
    ...t,
    notTranslated: t.notTranslated(code),
    noLocale: t.noLocale(code),
  }
}
